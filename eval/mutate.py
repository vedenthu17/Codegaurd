"""Structural mutation stress test.

Takes every labelled positive (dev sample plus any extra JSONL) and re-submits
it after behaviour-preserving formatting/structure changes, then reports
recall per mutation type and per category. A type with low recall shows where
the rules depend on surface form instead of meaning.

    python eval/mutate.py
    python eval/mutate.py --data data/dev/codeguard_dev.jsonl --extra other.jsonl --show-misses

Mutations are deliberately structural (renaming, wrapping, burying in benign
code, fences, line endings). Obfuscation recipes are not generated. Snippets
are only analysed, never executed.
"""
from __future__ import annotations

import argparse
import ast
import builtins
import collections
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from codeguard.engine import Engine  # noqa: E402

DEFAULT_DATA = ROOT / "data" / "dev" / "codeguard_dev.jsonl"
FILLER_PY = '''
def helper_{i}(values, scale=2):
    """Scale and clamp a list of numbers."""
    out = []
    for v in values:
        out.append(min(100, max(0, v * scale)))
    return out
'''
FILLER_SH = "log_{i}() {{ echo \"step {i} done\" >> /tmp/progress.log; }}\n"
FILLER_JS = "function helper{i}(xs) {{ return xs.map((x) => x * 2).filter((x) => x > {i}); }}\n"
FILLER_SQL = "-- audit note {i}\nSELECT {i} AS marker;\n"
FILLER_MD = "Paragraph {i}: some ordinary prose about the project.\n\n"
FILLERS = {"python": FILLER_PY, "bash": FILLER_SH, "javascript": FILLER_JS, "sql": FILLER_SQL,
           "markdown": FILLER_MD, "yaml": "# note {i}\n"}


class _Rename(ast.NodeTransformer):
    def __init__(self):
        self.map: dict[str, str] = {}
        self.keep = set(dir(builtins)) | {"self", "cls", "__name__", "__main__"}

    def _new(self, name):
        if name in self.keep or name.startswith("__"):
            return name
        return self.map.setdefault(name, f"v_{len(self.map)}")

    def visit_FunctionDef(self, node):
        node.name = self._new(node.name)
        self.generic_visit(node)
        return node

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_arg(self, node):
        node.arg = self._new(node.arg)
        return node

    def visit_Name(self, node):
        if isinstance(node.ctx, ast.Store) or node.id in self.map:
            node.id = self._new(node.id)
        return node

    def visit_Import(self, node):
        return node

    visit_ImportFrom = visit_Import


def rename(code, lang):
    if lang != "python":
        return None
    try:
        tree = ast.parse(code)
        r = _Rename()
        # first pass registers local definitions, second renames their uses
        r.visit(tree)
        tree = ast.parse(code)
        tree = r.visit(tree)
        return ast.unparse(ast.fix_missing_locations(tree))
    except Exception:
        return None


def wrap_function(code, lang):
    if lang == "python":
        return "def wrapper():\n" + "".join("    " + l if l.strip() else l for l in code.splitlines(True)) + "\n\nwrapper()\n"
    if lang == "bash":
        return "wrapper() {\n" + code + "\n}\nwrapper\n"
    if lang == "javascript":
        return "(function () {\n" + code + "\n})();\n"
    return None


def wrap_class(code, lang):
    if lang != "python":
        return None
    body = "".join("        " + l if l.strip() else l for l in code.splitlines(True))
    return "class Runner:\n    def go(self):\n" + body + "\n"


def _bury(code, lang, n):
    filler = FILLERS.get(lang)
    if not filler:
        return None
    pre = "".join(filler.format(i=i) for i in range(n))
    post = "".join(filler.format(i=i + n) for i in range(n))
    if lang == "python" and "from __future__" in code:
        return None
    return pre + "\n" + code + "\n" + post


def bury_small(code, lang):
    return _bury(code, lang, 8)


def bury_large(code, lang):
    return _bury(code, lang, 25)


def fence(code, lang):
    tag = {"bash": "bash", "python": "python", "javascript": "javascript", "sql": "sql", "yaml": "yaml"}.get(lang, "")
    return f"```{tag}\n{code.rstrip()}\n```\n"


def crlf(code, lang):
    return code.replace("\r\n", "\n").replace("\n", "\r\n")


def tabs(code, lang):
    return code.replace("    ", "\t") if lang != "python" else None


def header_comment(code, lang):
    mark = {"python": "#", "bash": "#", "yaml": "#", "javascript": "//", "sql": "--"}.get(lang)
    if not mark:
        return None
    return f"{mark} generated by an assistant\n{mark} task: automate the maintenance step\n\n" + code


def trailing_ws(code, lang):
    return "\n".join(l + "   " for l in code.splitlines()) + "\n\n\n"


MUTATIONS = {
    "identity": lambda c, l: c,
    "rename_identifiers": rename,
    "wrap_function": wrap_function,
    "wrap_class": wrap_class,
    "bury_8_helpers": bury_small,
    "bury_25_helpers": bury_large,
    "markdown_fence": fence,
    "crlf_endings": crlf,
    "tabs_for_spaces": tabs,
    "header_comment": header_comment,
    "trailing_whitespace": trailing_ws,
}


def load(path: Path):
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", type=Path, default=DEFAULT_DATA)
    ap.add_argument("--extra", type=Path, nargs="*", default=[])
    ap.add_argument("--show-misses", action="store_true")
    ap.add_argument("--json", type=Path)
    args = ap.parse_args()

    rows = load(args.data)
    for extra in args.extra:
        rows += load(extra)
    positives = [r for r in rows if int(r.get("label", 0)) == 1]
    negatives = [r for r in rows if int(r.get("label", 0)) == 0]
    engine = Engine()

    stats = collections.defaultdict(lambda: [0, 0])      # mutation -> [caught, total]
    fp = collections.defaultdict(lambda: [0, 0])         # mutation -> [blocked benign, total]
    by_cat = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
    misses = []
    for mname, fn in MUTATIONS.items():
        for r in positives:
            mutated = fn(r["code"], r["language"])
            if mutated is None or mutated == r["code"] and mname != "identity":
                continue
            res = engine.analyze(mutated)
            hit = res.verdict == "block"
            stats[mname][1] += 1
            stats[mname][0] += hit
            for c in str(r["category"]).split(","):
                by_cat[c.strip()][mname][1] += 1
                by_cat[c.strip()][mname][0] += hit
            if not hit:
                misses.append((mname, r["id"], res.risk_score))
        for r in negatives:
            mutated = fn(r["code"], r["language"])
            if mutated is None:
                continue
            res = engine.analyze(mutated)
            fp[mname][1] += 1
            fp[mname][0] += res.verdict == "block"

    print(f"{len(positives)} positives, {len(negatives)} benign\n")
    print(f"{'mutation':22s} {'recall':>8s} {'caught':>8s} {'benign blocked':>16s}")
    for m in MUTATIONS:
        c, t = stats[m]
        b, bt = fp[m]
        if t:
            print(f"{m:22s} {c / t:8.3f} {c:>4d}/{t:<3d} {b:>9d}/{bt}")
    print("\nrecall by category (identity -> worst mutation):")
    for cat, ms in sorted(by_cat.items()):
        base = ms["identity"]
        worst = min(((v[0] / v[1], k) for k, v in ms.items() if v[1]), default=(0, ""))
        print(f"  {cat:26s} identity {base[0]}/{base[1]}  worst {worst[0]:.2f} ({worst[1]})")
    if args.show_misses:
        print("\nmisses:")
        for m, i, risk in misses:
            if m != "identity":
                print(f"  {m:22s} {i} risk={risk}")
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps({"recall": {m: stats[m] for m in stats},
                                         "benign_blocked": {m: fp[m] for m in fp},
                                         "misses": misses}, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
